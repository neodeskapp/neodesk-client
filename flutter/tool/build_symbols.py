#!/usr/bin/env python3
"""Builds the icon fonts and NdIcons from the full Material Symbols font.

Every icon of the client comes from Material Symbols Outlined at weight 400,
grade 0, optical size 20, fill 0: the settings of the console's icon font
(web-ui/src/lib/styles/base.css, .material-icons). The app ships it as small
static subsets:

  assets/fonts/NdSymbols.ttf        fill 0, every icon in the list
  assets/fonts/NdSymbolsFilled.ttf  fill 1, only the icons marked filled

and lib/common/widgets/nd/nd_icons.dart, which names each icon, the one place
the client's code takes icons from. The list is tool/nd_symbols.txt, one icon
per line:

  <dart name> <symbol name> [filled]

where the symbol name is the one in Google's codepoints file (fonts.google.com/
icons shows it too) and "filled" takes the glyph from NdSymbolsFilled.ttf. An
icon with a meaning the console has (tool/console_icons.txt) takes that
meaning as its Dart name and the console's glyph.

To add an icon, add its line and run, from flutter/ (needs fonttools, tested
with 4.66.0):

  python3 tool/build_symbols.py

It downloads the variable font and its codepoints from the pinned commit of
github.com/google/material-design-icons, checks their SHA-256, and writes the
two fonts, nd_icons.dart and assets/fonts/MaterialSymbols-VERSION.txt (source,
font version, axes, the icons). With --src DIR it reads the two files from DIR
instead of downloading them (names as in the repository's variablefont/).
The output is the same on every run for the same list.
"""

import argparse
import hashlib
import os
import sys
import tempfile
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

COMMIT = "10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7"
BASE = (
    "https://raw.githubusercontent.com/google/material-design-icons/"
    + COMMIT
    + "/variablefont/"
)
FONT = "MaterialSymbolsOutlined[FILL,GRAD,opsz,wght].ttf"
CODEPOINTS = "MaterialSymbolsOutlined[FILL,GRAD,opsz,wght].codepoints"
SHA256 = {
    FONT: "f7837ba8573d9a7a74931618ced8307bc81f96d49af296bf6c8052c772ed5282",
    CODEPOINTS: "a7404d9e5a1b63f496cf05ace45d386075886b5a7f123fba9f29527cb6006fde",
}
AXES = {"GRAD": 0, "opsz": 20, "wght": 400}

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LIST = os.path.join(HERE, "nd_symbols.txt")
OUT_FONTS = {
    0: os.path.join(ROOT, "assets", "fonts", "NdSymbols.ttf"),
    1: os.path.join(ROOT, "assets", "fonts", "NdSymbolsFilled.ttf"),
}
OUT_DART = os.path.join(ROOT, "lib", "common", "widgets", "nd", "nd_icons.dart")
OUT_VERSION = os.path.join(ROOT, "assets", "fonts", "MaterialSymbols-VERSION.txt")

DART_HEAD = """\
// Material Symbols Outlined (weight 400, grade 0, optical size 20), as
// static subsets in assets/fonts/NdSymbols.ttf (fill 0) and
// NdSymbolsFilled.ttf (fill 1). Apache 2.0, see MaterialSymbols-LICENSE.txt.
// The client's only icons: names are the console's meanings (copy, files,
// password, ...) where it has one, glyph names otherwise.
//
// Generated by tool/build_symbols.py from tool/nd_symbols.txt. To add an
// icon, add its line to that list and run the script (see its header).

import 'package:flutter/widgets.dart';

class NdIcons {
  NdIcons._();

  static const _f = 'NdSymbols';
  static const _ff = 'NdSymbolsFilled';

"""


def fetch(src, tmp):
    """Returns local paths of the font and codepoints, checked. Downloads
    them into tmp when src is not given."""
    paths = {}
    for name in (FONT, CODEPOINTS):
        if src:
            path = os.path.join(src, name)
        else:
            path = os.path.join(tmp, name)
            url = BASE + urllib.request.quote(name)
            print("download", url)
            urllib.request.urlretrieve(url, path)
        with open(path, "rb") as f:
            got = hashlib.sha256(f.read()).hexdigest()
        if got != SHA256[name]:
            sys.exit(f"{path}: SHA-256 {got}, expected {SHA256[name]}")
        paths[name] = path
    return paths[FONT], paths[CODEPOINTS]


def read_list(codepoints):
    icons = []
    seen = set()
    with open(LIST, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.split("#", 1)[0].split()
            if not line:
                continue
            if len(line) not in (2, 3) or (len(line) == 3 and line[2] != "filled"):
                sys.exit(f"{LIST}:{n}: expected '<dart name> <symbol> [filled]'")
            dart, symbol = line[0], line[1]
            if dart in seen:
                sys.exit(f"{LIST}:{n}: {dart} is listed twice")
            if symbol not in codepoints:
                sys.exit(f"{LIST}:{n}: no symbol named {symbol}")
            seen.add(dart)
            icons.append((dart, symbol, codepoints[symbol], len(line) == 3))
    return sorted(icons)


def build_font(font_path, fill, unicodes, out):
    font = TTFont(font_path, recalcTimestamp=False)
    font = instancer.instantiateVariableFont(font, dict(AXES, FILL=fill))
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    sub = subset.Subsetter(options)
    sub.populate(unicodes=sorted(unicodes))
    sub.subset(font)
    font.recalcTimestamp = False
    font.save(out)
    print(f"wrote {os.path.relpath(out, ROOT)} ({os.path.getsize(out)} bytes)")


def write_version(font_path, icons):
    version = TTFont(font_path, lazy=True)["name"].getDebugName(5)
    lines = [
        "Material Symbols Outlined, static subsets for the NeoDesk client",
        "Upstream: https://github.com/google/material-design-icons/tree/"
        + COMMIT
        + "/variablefont",
        "License: Apache License 2.0 (MaterialSymbols-LICENSE.txt)",
        f"Font version: {version}",
        f"Source SHA-256: {SHA256[FONT]}",
        "Axes: "
        + ", ".join(f"{k}={v}" for k, v in sorted(AXES.items()))
        + ", FILL=0 (NdSymbols.ttf) and FILL=1 (NdSymbolsFilled.ttf)",
        "",
    ]
    for out in OUT_FONTS.values():
        with open(out, "rb") as f:
            got = hashlib.sha256(f.read()).hexdigest()
        lines.append(
            f"{os.path.basename(out)}: {os.path.getsize(out)} bytes, SHA-256 {got}"
        )
    symbols = sorted({symbol for _, symbol, _, _ in icons})
    filled = sorted({symbol for _, symbol, _, f in icons if f})
    lines += [
        "",
        f"Icons ({len(symbols)}): " + ",".join(symbols),
        f"Filled ({len(filled)}): " + ",".join(filled),
        "",
    ]
    with open(OUT_VERSION, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT_VERSION, ROOT)}")


def write_dart(icons):
    lines = [DART_HEAD]
    for dart, symbol, cp, filled in icons:
        family = "_ff" if filled else "_f"
        lines.append(
            f"  static const IconData {dart} = "
            f"IconData(0x{cp:x}, fontFamily: {family});\n"
        )
    lines.append("}\n")
    with open(OUT_DART, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(lines))
    print(f"wrote {os.path.relpath(OUT_DART, ROOT)} ({len(icons)} icons)")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--src", help="folder with the variable font and codepoints")
    args = ap.parse_args()
    with tempfile.TemporaryDirectory(prefix="nd-symbols-") as tmp:
        font_path, cp_path = fetch(args.src, tmp)
        codepoints = {}
        with open(cp_path, encoding="utf-8") as f:
            for line in f:
                name, cp = line.split()
                codepoints[name] = int(cp, 16)
        icons = read_list(codepoints)
        for fill, out in OUT_FONTS.items():
            unicodes = {cp for _, _, cp, f in icons if f or not fill}
            build_font(font_path, fill, unicodes, out)
        write_version(font_path, icons)
    write_dart(icons)


if __name__ == "__main__":
    main()
